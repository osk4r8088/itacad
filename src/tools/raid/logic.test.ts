import { describe, expect, it } from 'vitest';
import { writePenalty, arrayState, dataDisks, gfInv, gfMul, gfPow2, LEVELS, parityP, parityQ, recover, rebuildRead, stripe, stripeValues, tolerance, ureProbability, validDisks, type Level } from './logic';

/** All subsets of {0..n-1} with the given size. */
function subsets(n: number, size: number): number[][] {
  if (size === 0) return [[]];
  const out: number[][] = [];
  for (let i = 0; i < n; i++) for (const rest of subsets(n, size - 1)) if (rest.every((r) => r > i)) out.push([i, ...rest]);
  return out;
}

describe('GF(2^8)', () => {
  it('has a multiplicative inverse for every non-zero element', () => {
    for (let a = 1; a < 256; a++) expect(gfMul(a, gfInv(a))).toBe(1);
  });
  it('is generated by 2 with the polynomial 0x11d', () => {
    expect(gfPow2(8)).toBe(0x1d);
    expect(gfPow2(255)).toBe(1);
    expect(new Set(Array.from({ length: 255 }, (_, i) => gfPow2(i))).size).toBe(255);
  });
  it('distributes multiplication over XOR', () => {
    for (const [a, b, c] of [[3, 7, 200], [0x53, 0xca, 0x11], [255, 128, 1]]) expect(gfMul(a, b ^ c)).toBe(gfMul(a, b) ^ gfMul(a, c));
  });
});

describe('layout', () => {
  it('rotates RAID 5 parity left-symmetric: last disk first, one to the left per stripe', () => {
    expect([0, 1, 2, 3, 4].map((s) => stripe('5', 4, s).findIndex((b) => b.kind === 'p'))).toEqual([3, 2, 1, 0, 3]);
    // Data continues after the parity block and wraps: stripe 1 on 4 disks has P on disk 2, then D3 on disk 3, D4 on disk 0, D5 on disk 1.
    expect(stripe('5', 4, 1)).toEqual([{ kind: 'data', index: 4 }, { kind: 'data', index: 5 }, { kind: 'p' }, { kind: 'data', index: 3 }]);
  });
  it('puts RAID 6 Q right after P', () => {
    const s0 = stripe('6', 5, 0);
    expect(s0[4]).toEqual({ kind: 'p' });
    expect(s0[0]).toEqual({ kind: 'q' });
    expect(s0.slice(1, 4)).toEqual([0, 1, 2].map((index) => ({ kind: 'data', index })));
  });
  it('mirrors adjacent disks in RAID 10 (near layout)', () => {
    expect(stripe('10', 4, 0).map((b) => b.kind === 'data' && b.index)).toEqual([0, 0, 1, 1]);
    expect(stripe('10', 4, 1).map((b) => b.kind === 'data' && b.index)).toEqual([2, 2, 3, 3]);
  });
  it('stores every data block once per copy and keeps capacity consistent', () => {
    for (const level of LEVELS)
      for (let n = 2; n <= 8; n++) {
        if (!validDisks(level, n)) continue;
        const k = dataDisks(level, n);
        const copies = level === '1' ? n : level === '10' ? 2 : 1;
        const counts = new Map<number, number>();
        for (let s = 0; s < n; s++) for (const b of stripe(level, n, s)) if (b.kind === 'data') counts.set(b.index, (counts.get(b.index) ?? 0) + 1);
        expect(counts.size, `RAID ${level} n=${n}`).toBe(n * k);
        expect([...counts.values()].every((c) => c === copies)).toBe(true);
      }
  });
});

describe('recovery', () => {
  for (const level of LEVELS)
    for (let n = 2; n <= 7; n++) {
      if (!validDisks(level, n)) continue;
      it(`RAID ${level} with ${n} disks survives exactly what it should`, () => {
        const { guaranteed } = tolerance(level, n);
        for (let f = 0; f <= n; f++) {
          for (const failed of subsets(n, f)) {
            const set = new Set(failed);
            let survived = true;
            for (let s = 0; s < n; s++) {
              const original = stripeValues(level as Level, n, s).values;
              const r = recover(level as Level, n, s, set);
              r.forEach((x, d) => {
                if (x.ok) expect(x.value, `RAID ${level} n=${n} failed ${failed} stripe ${s} disk ${d}`).toBe(original[d]);
                else survived = false;
              });
            }
            if (f <= guaranteed) expect(survived, `RAID ${level} n=${n} failed ${failed}`).toBe(true);
            if (level === '10') {
              const pairLost = Array.from({ length: n / 2 }, (_, p) => set.has(2 * p) && set.has(2 * p + 1)).some(Boolean);
              expect(survived).toBe(!pairLost);
            } else if (f > guaranteed) expect(survived, `RAID ${level} n=${n} failed ${failed}`).toBe(false);
            expect(arrayState(level as Level, n, set)).toBe(f === 0 ? 'optimal' : survived ? 'degraded' : 'failed');
          }
        }
      });
    }
});

describe('write penalty', () => {
  it('is one I/O per copy for mirrors and read-modify-write for parity', () => {
    expect([writePenalty('0', 4), writePenalty('1', 2), writePenalty('1', 3), writePenalty('5', 4), writePenalty('6', 5), writePenalty('10', 4)]).toEqual([1, 2, 3, 4, 6, 2]);
  });
});

describe('parity', () => {
  it('computes P as XOR and Q as the weighted sum', () => {
    expect(parityP([0b1010, 0b0110])).toBe(0b1100);
    expect(parityQ([5, 7])).toBe(5 ^ gfMul(2, 7));
  });
});

describe('rebuild risk', () => {
  it('follows 1 - e^(-bits/rate)', () => {
    expect(ureProbability(0, 1e14)).toBe(0);
    // 12.5 TB = 1e14 bits: expected one error at 1e14, so the probability is 1 - 1/e.
    expect(ureProbability(12.5e12, 1e14)).toBeCloseTo(1 - Math.exp(-1), 10);
  });
  it('reads all surviving disks for RAID 5 and 6, one partner for RAID 10', () => {
    expect(rebuildRead('5', 4, 1e12)).toEqual({ bytes: 3e12, correctable: false });
    expect(rebuildRead('6', 5, 1e12)).toEqual({ bytes: 4e12, correctable: true });
    expect(rebuildRead('10', 4, 1e12)).toEqual({ bytes: 1e12, correctable: false });
    expect(rebuildRead('0', 2, 1e12)).toBeUndefined();
  });
});
